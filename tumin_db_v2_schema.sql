-- TUMIN Database v2 — PostgreSQL 14+
-- Jalankan hanya pada database BARU: tumin_db_v2. Tidak berisi DROP/TRUNCATE.
-- Dibuat berdasarkan query SQL server.ts dan tipe data src/types/index.ts.
BEGIN;

CREATE TABLE IF NOT EXISTS pengguna (
  id VARCHAR(80) PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  nama_lengkap VARCHAR(160) NOT NULL,
  email VARCHAR(254) UNIQUE,
  password VARCHAR(255) NOT NULL,
  peran VARCHAR(20) NOT NULL CHECK (LOWER(peran) IN ('owner','kasir')),
  aktif BOOLEAN NOT NULL DEFAULT TRUE,
  no_telepon VARCHAR(30),
  shift VARCHAR(40),
  dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  diperbarui_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mitra_seller (
  id VARCHAR(80) PRIMARY KEY,
  username VARCHAR(80) UNIQUE,
  nama_pemilik VARCHAR(160) NOT NULL,
  nama_toko VARCHAR(160) NOT NULL,
  no_telepon VARCHAR(30) NOT NULL,
  email VARCHAR(254),
  alamat TEXT,
  status VARCHAR(30) NOT NULL DEFAULT 'Pending',
  limit_piutang NUMERIC(16,2) NOT NULL DEFAULT 5000000 CHECK (limit_piutang >= 0),
  total_piutang_berjalan NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (total_piutang_berjalan >= 0),
  tanggal_transaksi_terakhir TIMESTAMPTZ,
  tanggal_daftar TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  catatan TEXT,
  password VARCHAR(255),
  CONSTRAINT mitra_seller_status_check CHECK (LOWER(status) IN ('pending','aktif','active','ditangguhkan','suspended','nonaktif'))
);
CREATE INDEX IF NOT EXISTS idx_mitra_seller_status ON mitra_seller (LOWER(status));

CREATE TABLE IF NOT EXISTS produk (
  id VARCHAR(80) PRIMARY KEY,
  sku VARCHAR(80) NOT NULL UNIQUE,
  nama_produk VARCHAR(200) NOT NULL,
  kategori VARCHAR(100) NOT NULL,
  harga_jual NUMERIC(16,2) NOT NULL CHECK (harga_jual >= 0),
  harga_pokok_modal NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (harga_pokok_modal >= 0),
  stok INTEGER NOT NULL DEFAULT 0 CHECK (stok >= 0),
  stok_minimum INTEGER NOT NULL DEFAULT 0 CHECK (stok_minimum >= 0),
  satuan VARCHAR(40) NOT NULL DEFAULT 'Pcs',
  deskripsi TEXT,
  gambar TEXT,
  terakhir_diperbarui TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pengaturan_toko (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  nama_toko VARCHAR(200) NOT NULL DEFAULT 'TUMIN',
  slogan TEXT,
  alamat TEXT,
  no_telepon VARCHAR(30),
  email_bisnis VARCHAR(254),
  nama_bank VARCHAR(100),
  nomor_rekening VARCHAR(100),
  atas_nama_rekening VARCHAR(160),
  jam_operasional VARCHAR(160),
  pesan_kaki_struk TEXT,
  stok_minimum_default INTEGER NOT NULL DEFAULT 10 CHECK (stok_minimum_default >= 0),
  dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  diperbarui_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS faktur_penjualan (
  id VARCHAR(100) PRIMARY KEY,
  nomor_faktur VARCHAR(100) NOT NULL UNIQUE,
  tanggal TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  nama_kasir VARCHAR(160) NOT NULL,
  metode_pembayaran VARCHAR(40) NOT NULL CHECK (metode_pembayaran IN ('Tunai','Transfer Bank','Kredit')),
  subtotal NUMERIC(16,2) NOT NULL CHECK (subtotal >= 0),
  diskon NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (diskon >= 0),
  total_akhir NUMERIC(16,2) NOT NULL CHECK (total_akhir >= 0),
  uang_diterima NUMERIC(16,2),
  uang_kembalian NUMERIC(16,2),
  nama_bank VARCHAR(100),
  nomor_referensi_transfer VARCHAR(160),
  foto_bukti_transfer TEXT,
  id_seller VARCHAR(80) REFERENCES mitra_seller(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  nama_seller VARCHAR(160),
  tanggal_jatuh_tempo DATE,
  jumlah_terbayar NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (jumlah_terbayar >= 0),
  sisa_tagihan NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK (sisa_tagihan >= 0),
  status_pembayaran VARCHAR(20) NOT NULL DEFAULT 'LUNAS' CHECK (status_pembayaran IN ('LUNAS','BELUM_LUNAS','SEBAGIAN')),
  CONSTRAINT faktur_kredit_seller_check CHECK (metode_pembayaran <> 'Kredit' OR id_seller IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_faktur_tanggal ON faktur_penjualan (tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_faktur_seller_tanggal ON faktur_penjualan (id_seller, tanggal DESC);

CREATE TABLE IF NOT EXISTS item_faktur (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_faktur VARCHAR(100) NOT NULL REFERENCES faktur_penjualan(id) ON UPDATE CASCADE ON DELETE CASCADE,
  id_produk VARCHAR(80) NOT NULL REFERENCES produk(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  sku_produk VARCHAR(80) NOT NULL,
  nama_produk VARCHAR(200) NOT NULL,
  jumlah INTEGER NOT NULL CHECK (jumlah > 0),
  harga_satuan NUMERIC(16,2) NOT NULL CHECK (harga_satuan >= 0),
  harga_pokok_satuan NUMERIC(16,2) CHECK (harga_pokok_satuan IS NULL OR harga_pokok_satuan >= 0),
  subtotal NUMERIC(16,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX IF NOT EXISTS idx_item_faktur_invoice ON item_faktur (id_faktur);
CREATE INDEX IF NOT EXISTS idx_item_faktur_produk ON item_faktur (id_produk);

CREATE TABLE IF NOT EXISTS cicilan_piutang (
  id VARCHAR(100) PRIMARY KEY,
  id_faktur VARCHAR(100) NOT NULL REFERENCES faktur_penjualan(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  tanggal TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  nominal_cicilan NUMERIC(16,2) NOT NULL CHECK (nominal_cicilan > 0),
  metode_pembayaran VARCHAR(40) NOT NULL CHECK (metode_pembayaran IN ('Tunai','Transfer Bank')),
  dicatat_oleh VARCHAR(160) NOT NULL,
  catatan TEXT,
  foto_bukti_transfer TEXT
);
CREATE INDEX IF NOT EXISTS idx_cicilan_faktur_tanggal ON cicilan_piutang (id_faktur, tanggal DESC);

CREATE TABLE IF NOT EXISTS mutasi_stok (
  id VARCHAR(120) PRIMARY KEY,
  tanggal TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  id_produk VARCHAR(80) NOT NULL REFERENCES produk(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  sku_produk VARCHAR(80) NOT NULL,
  nama_produk VARCHAR(200) NOT NULL,
  jenis_mutasi VARCHAR(40) NOT NULL CHECK (jenis_mutasi IN ('RESTOCK','PENJUALAN','KONSINYASI_KELUAR','KONSINYASI_RETUR','OPNAME_KOREKSI','RUSAK_REJECT')),
  jumlah_perubahan INTEGER NOT NULL,
  stok_sebelum INTEGER NOT NULL CHECK (stok_sebelum >= 0),
  stok_sesudah INTEGER NOT NULL CHECK (stok_sesudah >= 0),
  catatan TEXT,
  penanggung_jawab VARCHAR(160) NOT NULL,
  referensi VARCHAR(160)
);
CREATE INDEX IF NOT EXISTS idx_mutasi_produk_tanggal ON mutasi_stok (id_produk, tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_mutasi_tanggal ON mutasi_stok (tanggal DESC);

-- Tabel konsinyasi digunakan oleh API backend untuk mencatat penitipan dan pengurangan stok secara atomik.
CREATE TABLE IF NOT EXISTS barang_konsinyasi (
  id VARCHAR(100) PRIMARY KEY,
  id_seller VARCHAR(80) NOT NULL REFERENCES mitra_seller(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  id_produk VARCHAR(80) NOT NULL REFERENCES produk(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  sku_produk VARCHAR(80) NOT NULL,
  nama_produk VARCHAR(200) NOT NULL,
  jumlah_dititipkan INTEGER NOT NULL CHECK (jumlah_dititipkan > 0),
  harga_satuan NUMERIC(16,2) NOT NULL CHECK (harga_satuan >= 0),
  harga_jual_rekomendasi NUMERIC(16,2) NOT NULL CHECK (harga_jual_rekomendasi >= 0),
  tanggal_penitipan TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status VARCHAR(30) NOT NULL DEFAULT 'DITITIPKAN' CHECK (status IN ('DITITIPKAN','SEBAGIAN_TERJUAL','TERJUAL','DIKEMBALIKAN')),
  catatan TEXT
);
CREATE INDEX IF NOT EXISTS idx_konsinyasi_seller ON barang_konsinyasi (id_seller, tanggal_penitipan DESC);

-- Pengaturan default saja; tidak membuat akun/password demo.
INSERT INTO pengaturan_toko (id, nama_toko)
VALUES (1, 'TUMIN')
ON CONFLICT (id) DO NOTHING;

COMMIT;
